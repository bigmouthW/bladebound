let language = 'en';

export function normalizeLanguage(value) {
  return typeof value === 'string' && Object.hasOwn(messages, value) ? value : 'en';
}

export function setLanguage(value) { language = normalizeLanguage(value); }
export function getLanguage() { return language; }

export function t(key, values = {}) {
  const text = messages[language][key] ?? messages.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => values[name] === undefined ? match : String(values[name]));
}
